"""P6: property-based / adversarial tests for the solver + independent checker.

Each property is checked on random IO lists generated by fixed, reproducible
seeds, so a failure prints the exact seed that broke it.
"""
from hypothesis import given, settings, strategies as st

from app.models.rules import RuleSetConfig
from app.engine.generator import SyntheticGenerator
from app.engine.validator import DataValidator
from app.engine.solve.engine import solve_allocation
from app.engine.solve.bridge import rules_to_ref
from app.engine.hardware import hardware_for
from app.engine.io.template_writer import rows_from_allocations
import checker.check as chk


def _case(n: int, seed: int):
    gen = SyntheticGenerator(seed=seed)
    sig, ci = gen.generate_dataset(n_signals=n)
    sizes = {c["cable_id"]: c["size"] for c in ci}
    valid, _tqs, ledger = DataValidator().validate(sig, sizes)
    res, _prev, _raw = solve_allocation(valid, sizes, RuleSetConfig())
    return valid, sizes, res, ledger


@settings(max_examples=15, deadline=None)
@given(n=st.integers(min_value=20, max_value=120), seed=st.integers(min_value=0, max_value=10**6))
def test_coverage_is_always_one_hundred_percent(n, seed):
    valid, _sizes, res, ledger = _case(n, seed)
    placed = {s.tag for s in res.allocations if s.tag}
    held = {t for t, v in ledger.items() if v.startswith("held:")}
    held |= {t for q in res.tqs for t in (q.items or ())}
    # unique tags in the synthetic set; every signal is placed or held
    assert all(s.tag in placed or s.tag in held for s in valid)
    assert res.success, res.tqs[:2]


@settings(max_examples=15, deadline=None)
@given(n=st.integers(min_value=20, max_value=120), seed=st.integers(min_value=0, max_value=10**6))
def test_no_two_signals_share_a_physical_slot(n, seed):
    _valid, _sizes, res, _ledger = _case(n, seed)
    slots = [(a.cabinet, a.cioc, a.baseplate, a.slot)
             for a in res.allocations if a.tag]
    assert len(slots) == len(set(slots))


@settings(max_examples=15, deadline=None)
@given(n=st.integers(min_value=20, max_value=120), seed=st.integers(min_value=0, max_value=10**6))
def test_charm_matches_the_hardware_table(n, seed):
    _valid, _sizes, res, _ledger = _case(n, seed)
    for a in res.allocations:
        if not a.tag:
            continue
        charm, tb = hardware_for(a.io_type or "", a.subtype)
        assert a.charm == charm
        assert a.terminal_block == tb


@settings(max_examples=12, deadline=None)
@given(n=st.integers(min_value=20, max_value=120), seed=st.integers(min_value=0, max_value=10**6))
def test_independent_checker_agrees_with_a_clean_solve(n, seed):
    valid, sizes, res, ledger = _case(n, seed)
    held = {t for t, v in ledger.items() if v.startswith("held:")}
    held |= {t for q in res.tqs for t in (q.items or ())}
    io_rows = [{"tag": s.tag, "io_type": s.io_type, "subtype": s.subtype or "",
                "cable": s.cable, "pair": s.pair, "group": s.group or "",
                "seg": s.seg or ""} for s in valid]
    ref = rules_to_ref(RuleSetConfig())
    found = chk.check(io_rows, rows_from_allocations(res.allocations), ref,
                      ref.get("hardware_table"), sizes, frozenset(held))
    violations = [v for v in found if v["status"] == "violation"]
    assert violations == [], (seed, n, violations[:2])


@settings(max_examples=12, deadline=None)
@given(n=st.integers(min_value=20, max_value=120), seed=st.integers(min_value=0, max_value=10**6))
def test_solver_is_deterministic(n, seed):
    def rows():
        _valid, _sizes, res, _l = _case(n, seed)
        return [(a.tag, a.cabinet, a.cioc, a.baseplate, a.slot) for a in res.allocations]
    assert rows() == rows()
