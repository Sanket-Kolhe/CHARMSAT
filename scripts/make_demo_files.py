"""Generate demo/ sample files with fixed seeds (reproducible).

  demo/unseen_messy.xlsx   1,000-signal messy IO list (title rows, renamed +
                           shuffled headers, junk column, 2 sheets, 2 defects)
  demo/rev_b.xlsx          its Rev B (5% added, 2% deleted, type changes)
  demo/planted_ab_leak.xlsx  allocation export with a planted A/B leak
All generated by this script; no hand editing (seed 2026 / 99).
"""
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

import pandas as pd  # noqa: E402

from app.engine.generator import SyntheticGenerator  # noqa: E402
from app.engine.validator import DataValidator  # noqa: E402
from app.engine.solve.engine import solve_allocation  # noqa: E402
from app.models.rules import RuleSetConfig  # noqa: E402
from app.engine.io.template_writer import (  # noqa: E402
    load_template_map, write_template, rows_from_allocations)
import checker.check as checker_pkg  # noqa: E402

SEED = 2026
DEMO = ROOT / "demo"


def messy_grid(gen, sig, ci):
    df = gen.to_dataframe(sig, ci)
    df = df.rename(columns={"Tag": "TAG NO.", "IO Type": "Signal Type", "Cable": "Multicore",
                            "Pair": "PAIR", "Group": "Unit_Area", "Segregation": "Train",
                            "Cable Size": "Cable_Pairs", "Subtype": "Sub-Type"})
    df["Junk"] = "legacy"
    df = df[["Multicore", "TAG NO.", "Junk", "Signal Type", "PAIR", "Unit_Area",
             "Train", "Cable_Pairs", "Sub-Type"]]
    grid = [["UNSEEN CUSTOMER IO LIST - PLANT EXPANSION", "", "", "", "", "", "", "", ""],
            ["messy export - verify mapping on screen 1", "", "", "", "", "", "", "", ""]]
    grid += [list(df.columns)] + df.values.tolist()
    grid[4][1] = grid[3][1]  # duplicate tag defect
    cab = grid[5][0]          # A/B mix on another cable
    seen_a = False
    for r in grid[5:]:
        if r[0] == cab:
            r[6] = "A" if not seen_a else "B"
            seen_a = True
            if r[6] == "B":
                break
    return grid


def write_xlsx(path, sheets):
    with pd.ExcelWriter(path, engine="openpyxl") as w:
        for name, grid in sheets.items():
            pd.DataFrame(grid).to_excel(w, sheet_name=name, index=False, header=False)


def main():
    DEMO.mkdir(exist_ok=True)
    gen = SyntheticGenerator(seed=SEED)
    sig, ci = gen.generate_dataset(n_signals=1000)
    sizes = {c["cable_id"]: c["size"] for c in ci}

    grid = messy_grid(gen, sig, ci)
    write_xlsx(DEMO / "unseen_messy.xlsx", {"IO List": grid, "Notes": grid})
    print("wrote demo/unseen_messy.xlsx (1000 signals, messy)")

    sig_b, meta = gen.generate_revision_b(sig, cable_sizes=sizes)
    dfb = gen.to_dataframe(sig_b, [{"cable_id": c, "size": s} for c, s in meta["cable_sizes"].items()])
    with pd.ExcelWriter(DEMO / "rev_b.xlsx", engine="openpyxl") as w:
        dfb.to_excel(w, sheet_name="IO List", index=False)
    print(f"wrote demo/rev_b.xlsx (+{meta['added_count']}/-{meta['deleted_count']}/"
          f"~{meta['type_changed_count']} type changes)")

    rules = RuleSetConfig()
    valid, _, _ = DataValidator().validate(sig, sizes)
    res, _, _ = solve_allocation(valid, sizes, rules)
    tmap = load_template_map(ROOT / "data/templates/synthetic_map.yaml")
    clean = DEMO / "_clean.xlsx"
    write_template(ROOT / "data/templates/synthetic_template.xlsx", clean, tmap,
                   rows_from_allocations(res.allocations))
    planted = checker_pkg.plant_violation(
        clean.read_bytes(),
        {"allocation_sheet": tmap["allocation_sheet"],
         "first_data_row": tmap["first_data_row"], "columns": tmap["columns"]},
        "ab_leak")
    (DEMO / "planted_ab_leak.xlsx").write_bytes(planted)
    clean.unlink()
    print("wrote demo/planted_ab_leak.xlsx (checker must flag it)")


if __name__ == "__main__":
    main()
